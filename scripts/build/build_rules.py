"""Build rules/<DOMAIN>-<PREFIX>.yaml (e.g. D03-SLP.yaml) from rules/curated.yaml (active) + research/mining/*.md (drafts),
fill curated `values` from data/thresholds.yaml, write sources/provenance.csv, and lint.
Exit code 1 on any lint error."""
import re, sys, csv, yaml, pathlib, collections
ROOT = pathlib.Path(__file__).resolve().parents[2]
DOMAIN = {"SLP":"D03","INT":"D18","CON":"D02","TYP":"D05","CLR":"D06","TOK":"D04","LAY":"D07","CMP":"D08","MOT":"D09","A11":"D10",
          "ROB":"D15","CPY":"D11","DVZ":"D12","IMG":"D13","BRD":"D19","WEB":"D14","APP":"D14","IOS":"D14","AND":"D14","SLD":"D14",
          "PRN":"D14","SOC":"D14","EML":"D14","VID":"D14","PRC":"D17"}
MEDIA = {"WEB":["web"],"APP":["app"],"IOS":["ios"],"AND":["android"],"SLD":["slides"],"PRN":["print"],"SOC":["social"],"EML":["email"],"VID":["video"]}
PRIO = {"Floor":"P0","Reflex":"P1","Finish":"P3"}
errors = []

thr = yaml.safe_load((ROOT/"data/thresholds.yaml").read_text())["detectors"]
curated = yaml.safe_load((ROOT/"rules/curated.yaml").read_text())
cards = collections.defaultdict(list)
seen = set()
for c in curated:
    pid = c["id"].split("-")[0]
    if c["id"] in seen: errors.append(f"duplicate id {c['id']}")
    seen.add(c["id"])
    c.setdefault("priority", PRIO[c["tier"]]); c.setdefault("kind", "ban"); c.setdefault("check", "M")
    c.setdefault("waivable_by", "never" if c["tier"] == "Floor" else "brief"); c.setdefault("status", "active")
    if c["tier"] == "Floor" and c["waivable_by"] not in ("never", "brief"): errors.append(f"{c['id']}: Floor card must not be waivable")
    det = c.get("detector")
    if det:
        if det not in thr: errors.append(f"{c['id']}: detector '{det}' missing from thresholds.yaml")
        else:
            t = thr[det]
            if t.get("rule") != c["id"]: errors.append(f"{c['id']}: thresholds.{det}.rule is {t.get('rule')}")
            c["values"] = {k: v for k, v in t.items() if k not in ("rule", "tier")}
    for k in ("title", "rule", "why", "fix", "sources"):
        if not c.get(k): errors.append(f"{c['id']}: missing {k}")
    cards[pid].append(c)
for det, t in thr.items():
    if t.get("rule") not in seen: errors.append(f"thresholds.{det} cites {t.get('rule')} which has no curated card")

# mined drafts
row = re.compile(r"^\|\s*([A-Z0-9]{3})-(\d{3})\s*\|(.+)\|\s*$")
prov = []
counters = collections.Counter()
for f in sorted((ROOT/"research/mining").glob("[A-F]-*.md")):
    area = ""
    for line in f.read_text().splitlines():
        if line.startswith("### "): area = line[4:].strip()
        m = row.match(line)
        if not m: continue
        pid, num, rest = m.group(1), m.group(2), m.group(3)
        cols = [x.strip() for x in rest.split("|")]
        if len(cols) < 5 or pid not in DOMAIN: continue
        rule, values, tier, check, sources = cols[0], cols[1], cols[2], cols[3], cols[4]
        tier = tier if tier in PRIO else "Reflex"
        counters[pid] += 1
        new_id = f"{pid}-{100 + counters[pid]:03d}"
        card = {"id": new_id, "title": re.sub(r"[*`]", "", rule.split(";")[0].split(". ")[0])[:90], "domain": DOMAIN[pid],
                "tier": tier, "priority": PRIO[tier], "check": check if check in ("M","J","H") else "J", "rule": rule,
                "values": values if values not in ("—", "-", "") else None, "area": area,
                "sources": [s.strip() for s in re.split(r";\s*", sources) if s.strip()],
                "mined_from": f"{f.name}#{pid}-{num}", "status": "draft"}
        if pid in MEDIA: card["applies_when"] = MEDIA[pid]
        card = {k: v for k, v in card.items() if v is not None}
        cards[pid].append(card)
        prov.append([new_id, f.name, f"{pid}-{num}", "; ".join(card["sources"])])
for c in curated: prov.append([c["id"], "rules/curated.yaml", "", "; ".join(c["sources"])])

out = ROOT/"rules"
# Windows reserves CON, PRN, AUX, NUL, COM1-9 and LPT1-9 as file names (with any extension), so files are named
# <domain>-<prefix>.yaml. Rule ids (CON-101, PRN-012) are unchanged.
WIN_RESERVED = {"CON", "PRN", "AUX", "NUL", *(f"COM{i}" for i in range(1, 10)), *(f"LPT{i}" for i in range(1, 10))}
for old in out.glob("[A-Z0-9][A-Z0-9][A-Z0-9].yaml"): old.unlink()          # pre-8-Nov layout
for pid, lst in sorted(cards.items()):
    fname = f"{DOMAIN[pid]}-{pid}.yaml"
    if fname.split(".")[0].upper() in WIN_RESERVED: errors.append(f"{fname} is a reserved file name on Windows")
    (out/fname).write_text("# Generated by scripts/build/build_rules.py. Edit rules/curated.yaml or research/mining, not this file.\n"
                                   + yaml.safe_dump(lst, sort_keys=False, allow_unicode=True, width=140))
with open(ROOT/"sources/provenance.csv", "w", newline="") as fh:
    w = csv.writer(fh); w.writerow(["rule_id", "file", "mined_id", "sources"]); w.writerows(sorted(prov))

# A comma in an unquoted flow-style title splits it and leaves an empty key (found 9 Nov 2026 on CON-010, CON-016, CLR-016, CLR-019, LAY-007).
for l in cards.values():
    for c in l:
        empty = [k for k, v in c.items() if v is None]
        if empty: errors.append(f"{c['id']}: key(s) with no value {empty}; quote a title that contains a comma")
act = sum(1 for l in cards.values() for c in l if c["status"] == "active")
dr = sum(1 for l in cards.values() for c in l if c["status"] == "draft")
print(f"active {act}, draft {dr}, files {len(cards)}")
if errors:
    print("LINT ERRORS:"); [print(" -", e) for e in errors]; sys.exit(1)
print("lint ok")
